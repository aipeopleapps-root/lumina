# ── Queue-triggered worker dispatcher ───────────────────────────────────────
# Replaces the 3 separate AWS worker Lambdas — see module docstring above.

_WORKER_MODULES = {
    "pi_parse": "pi_parse",
    "pi_agent_lld": "pi_agent_lld",
    "pi_demo_generate": "pi_demo_generate",
    "rfp_reimagine": "rfp_reimagine",
    "test_automation": "test_automation",
}


@app.function_name(name="jobs_queue_dispatcher")
@app.queue_trigger(arg_name="msg", queue_name="jobs", connection="AzureWebJobsStorage")
def jobs_queue_dispatcher(msg: func.QueueMessage) -> None:
    try:
        message = json.loads(msg.get_body().decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        log.error("jobs queue: could not decode message id=%s, dropping", msg.id)
        return

    job_type = message.get("job_type")
    payload = message.get("payload") or {}
    module_name = _WORKER_MODULES.get(job_type)
    if module_name is None:
        log.error("jobs queue: unknown job_type %r (message id=%s), dropping", job_type, msg.id)
        return

    worker_fn = _handler(module_name, "worker_handler")
    log.info("jobs queue: dispatching job_type=%s message id=%s", job_type, msg.id)
    worker_fn(payload)


# ── Timer-triggered maintenance ──────────────────────────────────────────────
# Not a per-request handler, so it doesn't go through _handler()/invoke() — calls
# test_automation.reconcile_stale_executions() directly. See that function's
# docstring: sweeps every 15 minutes for Workday-execution scenarios whose
# container never called back (killed mid-execution, or its queue message was
# never picked up), so a run can't get stuck in pending/running forever.

@app.function_name(name="test_automation_reconcile_stale_executions")
@app.timer_trigger(schedule="0 */15 * * * *", arg_name="timer", run_on_startup=False, use_monitor=False)
def test_automation_reconcile_stale_executions(timer: func.TimerRequest) -> None:
    from test_automation.handler import reconcile_stale_executions
    reconcile_stale_executions()


