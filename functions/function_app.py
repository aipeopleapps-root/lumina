"""
Function App entry point — Phase 7.

One Azure Function App now hosts every ported handler, replacing AWS's 37
separate Lambda functions (`infra/lib/stack.ts`'s `makeFn` per handler). Two
kinds of Functions are registered here:

  - HTTP-triggered routes: one registration per `httpApi.addRoutes(...)` call
    in `stack.ts`, in the same order, translated 1:1 (`{param}` path syntax
    is identical between API Gateway v2 and Azure Functions route templates).
    Several routes intentionally point at the same handler module — e.g.
    `/manage/assign-consultant` and `/manage/assignments` both call
    `admin_assign_consultant.handler`, and every `/process-intelligence/
    {process_id}/...` route except `/parse` and `/plan` calls
    `pi_graph.handler`, which dispatches internally on `rawPath` (see
    `pi_graph.py`'s own dispatcher docstring) — this mirrors AWS exactly,
    where those routes were wired to the same Lambda function too.
  - One queue-triggered dispatcher, originally built to replace the 3
    separate AWS worker Lambdas (`generate_tests`/`pi_parse`/`pi_agent_lld`'s
    `worker_handler`, previously invoked via `lambda:InvokeFunction`). Azure
    has no function-to-function async invoke, so Phase 6 already changed the
    trigger handlers to enqueue `{job_type, payload}` onto the shared `jobs`
    Storage Queue (`functions/common/queue.py`); this dispatcher is the other
    half — it dequeues and routes by `job_type` to the matching worker
    module's `worker_handler(payload)`. `rfp_reimagine` (no AWS equivalent —
    a new post-migration feature) reuses this same async pattern rather than
    inventing a second one, since generating 4 documents runs past a sync
    request's time budget the same way the ported handlers' work did.

Every HTTP route requires a Function key (`auth_level=FUNCTION`) — APIM
(Phase 7 infra) is the only intended caller and injects the key on every
request via its `<set-header name="x-functions-key">` policy, regardless of
whether the *tenant* auth for that route is public
(`/mfa/request-reset`) or JWT-gated. Tenant/role auth itself is enforced two
layers down, inside each handler via `tenant_from_event()` — APIM's
`validate-jwt` policy only validates the Entra token and injects the
`x-tenant-id`/`x-user-role`/`x-user-sub`/`x-user-email` headers `tenant.py`
reads (see Phase 5); it does not decide per-route access, same division of
responsibility AWS had between API Gateway's JWT authorizer and each
Lambda's own `ctx.require_role(...)` calls.

`host.json` sets `extensions.http.routePrefix` to `""` so route paths here
match the AWS path strings exactly, with no `/api` prefix.

Every route below is a STATICALLY decorated top-level function — not
generated by looping over a table and calling `app.route(...)(fn)`
programmatically. That loop-based version is what this file originally had
(and what Phase 6/7 was authored, tested-via-mocks, and initially deployed
with) — it type-checks, it runs correctly under local `func host start`
testing, and the decorator calls themselves genuinely execute and mutate
`app`'s internal registry. It also silently produces ZERO indexed functions
on a real deployed Azure Functions Python v2 host: confirmed live (Phase 7
session 14) via a from-scratch bisection across 6 throwaway variants against
both a fresh `az functionapp create`d app and the real one — VNet
integration, DNS, RBAC, `AzureWebJobsStorage` access, and `common/`'s full
import chain (including real Cosmos/Foundry/OpenAI client construction) all
checked out fine in isolation; a hand-written static `@app.route` function
calling `importlib.import_module()`-resolved handler code worked
immediately; the exact same logic applied via the loop-and-reassign pattern
did not. The Python v2 worker's function-discovery step evidently needs
literal, statically-parseable `@app.route`/`@app.function_name` decorator
usage in source — not just objects that happen to have been correctly
registered on `app` by the time indexing runs. Each function below is
generated 1:1 from the same (name, route, methods, handler module) data the
old `_HTTP_ROUTES` table held, via a one-off script, specifically to avoid
transcribing 42 routes by hand and introducing a typo.
"""

